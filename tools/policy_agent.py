"""Policy-aware coverage decision.

Reads the actual policy document for the claim's policy type and decides whether
the incident is covered, producing human-readable reasoning that cites the
policy. This is what gets shown to the admin/reviewer: "Under our <type> policy
this incident IS / IS NOT covered because ...".

When an OpenAI key is present the reasoning is generated by the model grounded
in the policy text. Without a key it falls back to the structured INCIDENT_RULES
so the decision is still produced (just less verbose).
"""
from __future__ import annotations

import json
from typing import Any, Dict

import agentcore_client
import config
import database as db
import llm
import policy_rules


def decide_coverage(claim: Dict[str, Any]) -> Dict[str, Any]:
    """Return a coverage decision grounded in the policy document.

    Result keys:
      covered        -> True / False / None (unknown)
      policy_type    -> str
      reasoning      -> natural-language explanation citing the policy
      required_document -> what document the policy requires for this incident
      document_satisfied -> whether a document was supplied when one is required
    """
    policy_number = claim.get("policy_number")
    policy = db.get_policy(policy_number) if policy_number else None
    policy_type = policy["policy_type"] if policy else None
    incident_type = (claim.get("incident_type") or "").strip().lower()

    requirement = policy_rules.incident_requirement(incident_type)
    required_document = requirement.get("document_label") or ""
    document_required = requirement.get("document_required", False)
    document_supplied = bool(claim.get("document_path"))
    document_satisfied = document_supplied or not document_required

    policy_doc = policy_rules.load_policy_document(policy_type) if policy_type else None

    # --- LLM-grounded reasoning (preferred) --------------------------------
    if llm.is_available() and policy_doc:
        decision = _llm_decide(policy_doc, policy_type, incident_type, claim)
        if decision.get("covered") is not None:
            decision.update(
                {
                    "policy_type": policy_type,
                    "required_document": required_document,
                    "document_required": document_required,
                    "document_satisfied": document_satisfied,
                }
            )
            return decision
        # The model call failed (covered is None). Fall through to the rule-based
        # decision below so a model outage never auto-rejects a valid claim.

    # --- Deterministic fallback -------------------------------------------
    covered = requirement.get("covered")
    if policy_type and incident_type not in policy_rules.incident_types_for_policy(
        policy_type
    ):
        # Incident doesn't belong to this policy type at all.
        covered = False
        reasoning = (
            f"Under our {policy_type} policy, '{incident_type}' is not a listed "
            f"covered peril, so it is not covered."
        )
    elif covered is True:
        reasoning = (
            f"Under our {policy_type} policy, '{incident_type}' is a listed "
            f"covered peril, so it is covered subject to the deductible and limit."
        )
    elif covered is False:
        reasoning = (
            f"Under our {policy_type} policy, '{incident_type}' is explicitly "
            f"excluded, so it is not covered."
        )
    else:
        reasoning = (
            f"Coverage for '{incident_type}' could not be determined from the "
            f"{policy_type} policy."
        )

    return {
        "covered": covered,
        "policy_type": policy_type,
        "reasoning": reasoning,
        "required_document": required_document,
        "document_required": document_required,
        "document_satisfied": document_satisfied,
    }


def _llm_decide(
    policy_doc: str, policy_type: str, incident_type: str, claim: Dict[str, Any]
) -> Dict[str, Any]:
    if agentcore_client.enabled():
        # The hosted agent holds its own copy of the policy documents.
        try:
            data = agentcore_client.coverage_decision(policy_type, incident_type, claim)
            return {
                "covered": bool(data.get("covered")) if data.get("covered") is not None else None,
                "reasoning": str(data.get("reasoning") or "").strip(),
            }
        except Exception as exc:
            print(f"[agentcore] coverage_decision failed, using rules: {exc}")
            return {"covered": None, "reasoning": ""}
    prompt = (
        "You are an insurance coverage analyst. Using ONLY the policy document "
        "below, decide whether the claimed incident is covered. Cite the relevant "
        "clause in your reasoning. Respond as JSON with keys: "
        "covered (true/false), reasoning (string, 2-3 sentences).\n\n"
        f"=== {policy_type.upper()} POLICY DOCUMENT ===\n{policy_doc}\n\n"
        f"=== CLAIM ===\n"
        f"Incident type: {incident_type}\n"
        f"Incident date: {claim.get('incident_date')}\n"
        f"Description: {claim.get('description')}\n"
        f"Claimed amount: {claim.get('claimed_amount')}\n"
    )
    try:
        data = json.loads(llm.complete(prompt, json_mode=True, max_tokens=600))
        return {
            "covered": bool(data.get("covered")),
            "reasoning": data.get("reasoning", "").strip(),
        }
    except Exception:
        return {"covered": None, "reasoning": ""}
